APPROVAL_FILTER = {"notifyMemberIds": {"anyOf"}, "requestorId": {"equals"}, "resourceId": {"equals"},
                   "resourceKind": {"equals"}, "reviewStatus": {"anyOf"}, "status": {"anyOf"}, "projectKey": {"equals"}}


def r_approvals(q, path, _m):
    terms = op_filter(one(q, "filter"), APPROVAL_FILTER)
    expand_set(q, {"flag", "project", "environments"})
    items = []
    for a in ACCOUNT["approval_requests"]:
        rid = a.get("resourceId", "")
        segs = [s.split("/", 1) for s in rid.split(":")]
        keep = True
        for field, _op, val in terms:
            if field == "notifyMemberIds":
                keep &= bool(set(val) & set(a["notifyMemberIds"]))
            elif field == "requestorId":
                keep &= a.get("requestorId") == val
            elif field == "resourceId":
                keep &= rid == val
            elif field == "resourceKind":
                if val not in ("flag", "segment", "aiConfig"):
                    raise bad("resourceKind must be flag, segment or aiConfig")
                keep &= segs[-1][0] == val
            elif field == "reviewStatus":
                keep &= a["reviewStatus"] in val
            elif field == "status":
                keep &= a["status"] in val
            elif field == "projectKey":
                keep &= segs[0] == ["proj", val]
        if keep:
            items.append(a)
    return page(q, items, path, 20, 200)


