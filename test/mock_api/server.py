class ApiError(Exception):
    def __init__(self, status: int, code: str, message: str, headers: dict | None = None):
        super().__init__(message)
        self.status, self.code, self.message, self.headers = status, code, message, headers or {}


def bad(message: str) -> ApiError:
    return ApiError(400, "invalid_request", message)


def not_found(what: str) -> ApiError:
    return ApiError(404, "not_found", f"Unknown {what}")


# ------------------------------------------------------------------- helpers


def one(q: dict, name: str) -> str | None:
    v = q.get(name)
    if v is None:
        return None
    if len(v) != 1:
        raise bad(f"{name} must be given once")
    return v[0]


def int_param(q: dict, name: str, default: int, lo: int, hi: int) -> int:
    v = one(q, name)
    if v is None:
        return default
    if not re.fullmatch(r"\d+", v) or not lo <= int(v) <= hi:
        raise bad(f"{name} must be an integer between {lo} and {hi}")
    return int(v)


def split_top(s: str, sep: str = ",") -> list[str]:
    """Split on ``sep`` outside braces, brackets and double quotes."""
    out, depth, cur, inq = [], 0, "", False
    for ch in s:
        if ch == '"':
            inq = not inq
        elif not inq and ch in "{[(":
            depth += 1
        elif not inq and ch in "}])":
            depth -= 1
        if ch == sep and depth == 0 and not inq:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return [x.strip() for x in out if x.strip()]


def colon_filter(raw: str | None, supported: set[str], documented: set[str] = frozenset()) -> dict[str, str]:
    """Parse ``field:value,field:value``; reject unknown fields."""
    out: dict[str, str] = {}
    if raw is None:
        return out
    for part in split_top(raw):
        if ":" not in part:
            raise bad(f"invalid filter term {part!r} (expected field:value)")
        k, v = part.split(":", 1)
        if k in documented and k not in supported:
            raise bad(f"filter field {k!r} is documented but not supported by the fixture server")
        if k not in supported:
            raise bad(f"unknown filter field {k!r}")
        if k in out:
            raise bad(f"filter field {k!r} given twice")
        out[k] = v
    return out


OP_RE = re.compile(r"^([A-Za-z]+)\s+(equals|anyOf|contains|notEquals|exists)\s*(.*)$", re.S)


def op_filter(raw: str | None, supported: dict[str, set[str]]) -> list[tuple[str, str, object]]:
    """Parse the operator syntax ``field op value`` joined by commas (no | or parentheses)."""
    out: list[tuple[str, str, object]] = []
    if raw is None:
        return out
    if "|" in raw.replace('"|"', ""):
        raise bad("the fixture server does not support | in operator filters")
    for part in split_top(raw):
        m = OP_RE.match(part)
        if not m:
            raise bad(f"invalid filter term {part!r} (expected 'field operator value')")
        field, op, val = m.group(1), m.group(2), m.group(3).strip()
        if field not in supported:
            raise bad(f"unknown or unsupported filter field {field!r}")
        if op not in supported[field]:
            raise bad(f"filter field {field!r} does not support {op!r}")
        if op in ("anyOf", "contains"):
            try:
                parsed = json.loads(val)
            except ValueError as err:
                raise bad(f"{field} {op} needs a JSON array") from err
            if not isinstance(parsed, list):
                raise bad(f"{field} {op} needs a JSON array")
            out.append((field, op, parsed))
        elif op == "exists":
            out.append((field, op, None))
        else:
            if val.startswith('"'):
                try:
                    val = json.loads(val)
                except ValueError as err:
                    raise bad(f"bad quoted value for {field}") from err
            elif val in ("true", "false"):
                val = val == "true"
            out.append((field, op, val))
    return out


def page(q: dict, items: list, path: str, default_limit: int, max_limit: int, total_key: str = "totalCount") -> dict:
    limit = int_param(q, "limit", default_limit, 1, max_limit)
    offset = int_param(q, "offset", 0, 0, 10**9)
    chunk = items[offset : offset + limit]
    links = {"self": {"href": path, "type": "application/json"}}
    if offset + limit < len(items):
        params = {k: v for k, v in q.items() if k != "offset"}
        params["offset"] = [str(offset + limit)]
        params["limit"] = [str(limit)]
        links["next"] = {"href": f"{path}?{urlencode(params, doseq=True)}", "type": "application/json"}
    return {"items": chunk, total_key: len(items), "_links": links}


def project(key: str) -> dict:
    for p in ACCOUNT["projects"]:
        if p["key"] == key:
            return p
    raise not_found("project")


def env_keys(p: dict) -> list[str]:
    return [e["key"] for e in p["environments"]]


def strip_private(d: dict) -> dict:
    return {k: v for k, v in d.items() if not k.startswith("__")}


def iso_ms(v: str | None) -> int | None:
    if not v:
        return None
    return int(dt.datetime.fromisoformat(v.replace("Z", "+00:00")).timestamp() * 1000)


def expand_set(q: dict, allowed: set[str]) -> set[str]:
    v = one(q, "expand")
    if not v:
        return set()
    got = {x.strip() for x in v.split(",") if x.strip()}
    if got - allowed:
        raise bad(f"unknown expand field(s): {sorted(got - allowed)}")
    return got


