def r_experiments(q, path, m):
    project(m[1])
    f = colon_filter(one(q, "filter"), {"flagKey", "metricKey", "status"})
    exp = expand_set(q, {"previousIterations", "draftIteration", "secondaryMetrics", "treatments", "analysisConfig"})
    ls = one(q, "lifecycleState") or "active"
    states = set(ls.split(","))
    if states - {"active", "archived"}:
        raise bad("lifecycleState must be active, archived or both")
    items = []
    for ex in ACCOUNT["experiments"].get(m[1], []):
        st = "archived" if ex.get("archivedDate") else "active"
        if st not in states:
            continue
        it = ex.get("currentIteration") or {}
        if "flagKey" in f and f["flagKey"] not in it.get("flags", {}):
            continue
        if "metricKey" in f and f["metricKey"] not in [x["key"] for x in it.get("metrics", [])]:
            continue
        if "status" in f:
            if f["status"] not in ("not_started", "running", "stopped"):
                raise bad("status must be not_started, running or stopped")
            if it.get("status") != f["status"]:
                continue
        out = copy.deepcopy(ex)
        if "treatments" not in exp and "currentIteration" in out:
            out["currentIteration"].pop("treatments", None)
        items.append(out)
    return page(q, items, path, 20, 50, total_key="total_count")


METRIC_FILTER = {"query": {"equals"}, "eventKind": {"equals"}, "isNumeric": {"equals"}, "tags": {"contains"}}


def r_metrics(q, path, m):
    project(m[1])
    terms = op_filter(one(q, "filter"), METRIC_FILTER)
    expand_set(q, {"experimentCount", "metricGroupCount", "activeExperimentCount", "activeGuardedRolloutCount"})
    sort = one(q, "sort")
    if sort and sort.lstrip("-") not in {"createdAt", "name"}:
        raise bad(f"unknown sort field {sort!r}")
    items = []
    for mt in ACCOUNT["metrics"].get(m[1], []):
        keep = True
        for field, _op, val in terms:
            if field == "query":
                keep &= isinstance(val, str) and val.lower() in (mt["key"] + " " + mt["name"]).lower()
            elif field == "eventKind":
                if val not in ("custom", "pageview", "click"):
                    raise bad("eventKind must be custom, pageview or click")
                keep &= mt["kind"] == val
            elif field == "isNumeric":
                if not isinstance(val, bool):
                    raise bad("isNumeric equals needs true or false")
                keep &= mt.get("isNumeric", False) == val
            elif field == "tags":
                keep &= set(val) <= set(mt["tags"])
        if keep:
            items.append(mt)
    return page(q, items, path, 20, 50)


def r_pipelines(q, path, m):
    project(m[1])
    f = colon_filter(one(q, "filter"), {"query", "env"})
    items = []
    for rp in ACCOUNT["release_pipelines"].get(m[1], []):
        if "query" in f and f["query"].lower() not in " ".join([rp["key"], rp["name"], rp.get("description", "")]).lower():
            continue
        if "env" in f and f["env"] not in [a["environment"]["key"] for ph in rp["phases"] for a in ph["audiences"]]:
            continue
        items.append(rp)
    return page(q, items, path, 20, 100)


def r_repos(q, path, _m):
    with_branches = one(q, "withBranches") is not None
    with_refs = one(q, "withReferencesForDefaultBranch") is not None
    proj, flag = one(q, "projKey"), one(q, "flagKey")
    if proj is not None:
        project(proj)
    items = []
    for r in ACCOUNT["repositories"]:
        out = {k: v for k, v in r.items() if k != "branches"}
        if with_refs:
            branches = []
            for b in r["branches"]:
                if b["name"] != r["defaultBranch"]:
                    continue
                refs = []
                for ref in b["references"]:
                    hunks = [h for h in ref["hunks"] if (proj is None or h["projKey"] == proj) and (flag is None or h["flagKey"] == flag)]
                    if hunks:
                        refs.append({**ref, "hunks": hunks})
                branches.append({**b, "references": refs})
            out["branches"] = branches
        elif with_branches:
            out["branches"] = [{k: v for k, v in b.items() if k != "references"} for b in r["branches"]]
        items.append(out)
    return {"items": items, "_links": {"self": {"href": path}}}


def spec_matches(spec: str, resource: str) -> bool:
    a = [s.split("/", 1) for s in spec.split(":")]
    b = [s.split("/", 1) for s in resource.split(":")]
    if len(a) != len(b):
        return False
    for (ta, *na), (tb, *nb) in zip(a, b):
        if ta != tb:
            return False
        name_a = (na[0] if na else "").split(";")[0]
        name_b = (nb[0] if nb else "").split(";")[0]
        if not fnmatch.fnmatchcase(name_b, name_a or "*"):
            return False
    return True


SPEC_RE = re.compile(r"^[a-z\-]+(/[^:]*)?(:[a-z\-]+(/[^:]*)?)*$")


def r_auditlog(q, path, _m):
    limit = int_param(q, "limit", 10, 1, 20)
    before = one(q, "before")
    after = one(q, "after")
    for name, v in (("before", before), ("after", after)):
        if v is not None and not re.fullmatch(r"\d+", v):
            raise bad(f"{name} must be a unix timestamp in milliseconds")
    spec = one(q, "spec")
    if spec is not None and not SPEC_RE.match(spec):
        raise bad(f"invalid resource specifier {spec!r}")
    text = one(q, "q")
    members, tokens = q.get("member", []), q.get("token", [])
    rows = []
    for e in ACCOUNT["auditlog"]:
        if before is not None and not e["date"] < int(before):
            continue
        if after is not None and not e["date"] > int(after):
            continue
        if text and text.lower() not in " ".join([e["name"], e["description"], e.get("title", "")]).lower():
            continue
        if spec and not any(spec_matches(spec, r) for r in e["target"]["resources"]):
            continue
        if members and (e.get("member") or {}).get("_id") not in members:
            continue
        if tokens and (e.get("token") or {}).get("_id") not in tokens:
            continue
        rows.append(strip_private(e))
    chunk = rows[:limit]
    links = {"self": {"href": path}}
    if len(rows) > limit:
        params = dict(q)
        params["before"] = [str(chunk[-1]["date"])]
        links["next"] = {"href": f"{path}?{urlencode(params, doseq=True)}", "type": "application/json"}
    return {"items": chunk, "_links": links}


def r_audit_entry(q, path, m):
    for e in ACCOUNT["auditlog"]:
        if e["_id"] == m[1]:
            out = strip_private(e)
            out.update({k: v for k, v in (e.get("__detail") or {}).items() if v is not None})
            return out
    raise not_found("audit log entry")


