#!/usr/bin/env python3
"""A strict, offline LaunchDarkly REST API v2 replay server for the tests (stdlib only).

It serves the account in ``test/fixtures/launchdarkly-account.json`` (documented
LaunchDarkly response shapes, generated by ``test/fixtures/build_fixture.py``) and
behaves like LaunchDarkly where the worker depends on it:

* **Auth.** ``Authorization: api-test-token`` (LaunchDarkly takes the raw token, no
  scheme); anything else is a 401 ``{"code": "unauthorized"}``. Every request must also
  pin ``LD-API-Version: 20240415`` (400 otherwise; ``beta`` is rejected because none of
  these endpoints is a beta endpoint).
* **Strict parameters.** Each route accepts only its documented query parameters; an
  unknown parameter, a bad ``limit``/``offset``, an unknown ``env``, ``sort`` or
  ``expand`` value, or an unparsable / unsupported ``filter`` is a 400.
* **Filters are evaluated**, so pushdown really narrows the data: the flags
  ``field:value`` filter (query, tags, state, archived, type, maintainerId,
  maintainerTeamKey, sdkAvailability, creationDate, evaluated + filterEnv,
  hasExperiment), the projects / environments / members / teams / experiments /
  release-pipeline ``field:value`` filters, and the operator syntax (``equals``,
  ``anyOf``, ``contains``, ``exists``) of segments, approvals and metrics.
* **Flags.** Archived flags are omitted unless filtered for; ``env`` selects the
  environment configs returned (none without it); without ``summary=0`` the rules,
  targets and prerequisites are stripped, as LaunchDarkly does.
* **Audit log.** Entries newest first; ``after`` / ``before`` (epoch ms, exclusive),
  ``q``, ``member`` / ``token`` (repeatable) and ``spec`` (a resource specifier with
  ``*`` wildcards, matched segment by segment against each entry's target resources).
  ``limit`` 1-20; the next page is ``_links.next`` with ``before`` = the last date.
  Entries with ``date_offset_minutes`` are dated relative to server start.
* **Paging.** ``limit`` / ``offset`` with ``totalCount`` and a ``_links.next`` that keeps
  every parameter.
* **Rate limits.** ``X-Ratelimit-Global-Remaining`` / ``-Route-Remaining`` /
  ``X-Ratelimit-Reset`` (epoch ms) on every response; the first ``/api/v2/teams``
  request answers 429 (route bucket empty, reset in 1 s, ``Retry-After: 1``) and the first
  ``/api/v2/roles`` request answers 503, so the retry paths always run.
* **Introspection.** ``GET /__requests?path=/api/v2/flags/default`` returns every
  recorded request to that path (``seq``, ``path``, ``query`` as a JSON object string with
  repeated parameters as lists, ``auth`` ok/bad) so SQL tests can assert exactly what was
  pushed down.

Usage::

    python3 test/mock_api/server.py            # prints PORT:<n> once listening
"""

