def r_members(q, path, _m):
    f = colon_filter(one(q, "filter"), {"query", "role", "id", "email", "team", "noteam", "lastSeen"}, {"accessCheck"})
    expand_set(q, {"customRoles", "roleAttributes"})
    sort = one(q, "sort")
    if sort and sort.lstrip("-") not in {"displayName", "lastSeen"}:
        raise bad(f"unknown sort field {sort!r}")
    items = []
    for mem in ACCOUNT["members"]:
        role = "admin" if mem["role"] == "owner" else mem["role"]
        if "query" in f and f["query"].lower() not in " ".join([mem["email"], mem["firstName"], mem["lastName"]]).lower():
            continue
        if "role" in f and not ({role} | set(mem["customRoles"])) & set(f["role"].split("|")):
            continue
        if "id" in f and mem["_id"] not in f["id"].split("|"):
            continue
        if "email" in f and mem["email"] not in f["email"].split("|"):
            continue
        if "team" in f and f["team"].lower() not in [t["key"].lower() for t in mem["teams"]]:
            continue
        if "noteam" in f and (len(mem["teams"]) == 0) != (f["noteam"] == "true"):
            continue
        if "lastSeen" in f:
            ls = json.loads(f["lastSeen"])
            if ls.get("never") and mem["_lastSeen"]:
                continue
            if "before" in ls and not (mem["_lastSeen"] and mem["_lastSeen"] < ls["before"]):
                continue
        items.append(mem)
    return page(q, items, path, 20, 1000)


def r_teams(q, path, _m):
    f = colon_filter(one(q, "filter"), {"query", "nomembers"})
    exp = expand_set(q, {"members", "roles", "roleAttributes", "projects", "maintainers"})
    sort = one(q, "sort")
    if sort and sort.lstrip("-") not in {"name", "memberCount"}:
        raise bad(f"unknown sort field {sort!r}")
    items = []
    for t in ACCOUNT["teams"]:
        if "query" in f and f["query"].lower() not in (t["key"] + " " + t["name"]).lower():
            continue
        if "nomembers" in f and (len(t["memberIds"]) == 0) != (f["nomembers"] == "true"):
            continue
        out = {k: v for k, v in t.items() if k not in ("memberIds", "roleKeys")}
        if "members" in exp:
            out["members"] = {"totalCount": len(t["memberIds"])}
        if "roles" in exp:
            roles = [r for r in ACCOUNT["roles"] if r["key"] in t["roleKeys"]]
            out["roles"] = {"totalCount": len(roles), "items": [{"key": r["key"], "name": r["name"]} for r in roles]}
        items.append(out)
    return page(q, items, path, 20, 100)


