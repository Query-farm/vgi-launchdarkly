def r_projects(q, path, _m):
    f = colon_filter(one(q, "filter"), {"query", "tags", "keys"})
    sort = one(q, "sort")
    if sort and sort.lstrip("-") not in {"name", "createdOn"}:
        raise bad(f"unknown sort field {sort!r}")
    exp = expand_set(q, {"environments"})
    items = []
    for p in ACCOUNT["projects"]:
        if "query" in f and f["query"].lower() not in (p["key"] + " " + p["name"]).lower():
            continue
        if "tags" in f and not set(f["tags"].split(" ")) <= set(p["tags"]):
            continue
        if "keys" in f and p["key"] not in f["keys"].split("|"):
            continue
        out = {k: v for k, v in p.items() if k not in ("environments", "createdOn")}
        out["_links"] = {"self": {"href": f"/api/v2/projects/{p['key']}"}}
        if "environments" in exp:
            out["environments"] = {"items": p["environments"], "totalCount": len(p["environments"])}
        items.append(out)
    if sort:
        items.sort(key=lambda x: x["name"], reverse=sort.startswith("-"))
    return page(q, items, path, 20, 1000)


def r_environments(q, path, m):
    p = project(m[1])
    f = colon_filter(one(q, "filter"), {"query", "tags", "critical"})
    sort = one(q, "sort")
    if sort and sort.lstrip("-") not in {"createdOn", "critical", "name"}:
        raise bad(f"unknown sort field {sort!r}")
    items = []
    for e in p["environments"]:
        if "query" in f and f["query"].lower() not in (e["key"] + " " + e["name"]).lower():
            continue
        if "tags" in f and not set(f["tags"].split(" ")) <= set(e["tags"]):
            continue
        if "critical" in f:
            if f["critical"] not in ("true", "false"):
                raise bad("critical must be true or false")
            if e["critical"] != (f["critical"] == "true"):
                continue
        items.append(e)
    return page(q, items, path, 20, 200)


FLAG_FILTER_SUPPORTED = {
    "query", "tags", "state", "archived", "type", "maintainerId", "maintainerTeamKey", "sdkAvailability",
    "creationDate", "evaluated", "filterEnv", "hasExperiment",
}
FLAG_FILTER_DOCUMENTED = FLAG_FILTER_SUPPORTED | {
    "applicationEvaluated", "contextKindsEvaluated", "codeReferences.max", "codeReferences.min",
    "guardedRollout", "releasePipeline",
}
FLAG_SORTS = {"creationDate", "key", "maintainerId", "name", "tags", "targetingModifiedDate", "type"}


def experiment_flag_keys(project_key: str) -> set[str]:
    out = set()
    for ex in ACCOUNT["experiments"].get(project_key, []):
        out |= set((ex.get("currentIteration") or {}).get("flags", {}).keys())
    return out


def r_flags(q, path, m):
    p = project(m[1])
    envs = q.get("env", [])
    for e in envs:
        if e not in env_keys(p):
            raise bad(f"unknown environment {e!r}")
    f = colon_filter(one(q, "filter"), FLAG_FILTER_SUPPORTED, FLAG_FILTER_DOCUMENTED)
    summary = one(q, "summary")
    if summary is not None and summary not in ("0", "1", "true", "false"):
        raise bad("summary must be 0/1/true/false")
    full = summary in ("0", "false")
    if one(q, "compare") is not None:
        raise bad("compare is unavailable in API version 20240415")
    expand_set(q, {"evaluation", "codeReferences", "archivedSettings", "migrationSettings"})
    sort = one(q, "sort")
    if sort:
        for s in sort.split(","):
            if s.lstrip("-") not in FLAG_SORTS:
                raise bad(f"unknown sort field {s!r}")
    tag = one(q, "tag")
    archived_param = one(q, "archived")
    env_specific = {"evaluated"}
    if env_specific & set(f) and "filterEnv" not in f:
        raise bad("filter field 'evaluated' requires filterEnv")
    if "filterEnv" in f and f["filterEnv"] not in env_keys(p):
        raise bad(f"unknown filterEnv {f['filterEnv']!r}")
    exp_flags = experiment_flag_keys(p["key"])
    items = []
    for fl in ACCOUNT["flags"].get(p["key"], []):
        state = "archived" if fl["archived"] else "deprecated" if fl.get("deprecated") else "live"
        if "state" in f:
            if f["state"] not in ("live", "deprecated", "archived"):
                raise bad("state must be live, deprecated or archived")
            if state != f["state"]:
                continue
        elif f.get("archived") == "true" or archived_param == "true":
            if not fl["archived"]:
                continue
        elif fl["archived"]:
            continue  # archived flags are omitted unless asked for
        if "query" in f and f["query"].lower() not in (fl["key"] + " " + fl["name"]).lower():
            continue
        tags = set(f["tags"].split(" ")) if "tags" in f else set()
        if tag:
            tags.add(tag)
        if not tags <= set(fl["tags"]):
            continue
        if "type" in f:
            if f["type"] not in ("temporary", "permanent"):
                raise bad("type must be temporary or permanent")
            if fl["temporary"] != (f["type"] == "temporary"):
                continue
        if "maintainerId" in f and fl.get("maintainerId") != f["maintainerId"]:
            continue
        if "maintainerTeamKey" in f and fl.get("maintainerTeamKey") != f["maintainerTeamKey"]:
            continue
        if "sdkAvailability" in f:
            csa = fl["clientSideAvailability"]
            want = f["sdkAvailability"]
            ok = {
                "client": csa["usingEnvironmentId"],
                "mobile": csa["usingMobileKey"],
                "anyClient": csa["usingEnvironmentId"] or csa["usingMobileKey"],
                "server": not (csa["usingEnvironmentId"] or csa["usingMobileKey"]),
            }
            if want not in ok:
                raise bad("sdkAvailability must be client, mobile, anyClient or server")
            if not ok[want]:
                continue
        if "creationDate" in f:
            try:
                cd = json.loads(f["creationDate"])
            except ValueError as err:
                raise bad("creationDate must be a JSON object") from err
            if set(cd) - {"before"} or not isinstance(cd.get("before"), int):
                raise bad('creationDate must look like {"before": <unix ms>}')
            if not fl["creationDate"] < cd["before"]:
                continue
        if "evaluated" in f:
            try:
                ev = json.loads(f["evaluated"])
            except ValueError as err:
                raise bad("evaluated must be a JSON object") from err
            if set(ev) != {"after"} or not isinstance(ev["after"], int):
                raise bad('evaluated must look like {"after": <unix ms>}')
            st = ACCOUNT["flag_statuses"][f"{p['key']}/{f['filterEnv']}"].get(fl["key"])
            last = iso_ms(st[1]) if st else None
            if last is None or last <= ev["after"]:
                continue
        if "hasExperiment" in f and (fl["key"] in exp_flags) != (f["hasExperiment"] == "true"):
            continue
        out = copy.deepcopy(fl)
        if envs:
            out["environments"] = {k: v for k, v in out["environments"].items() if k in envs}
            if not full:
                for c in out["environments"].values():
                    for k in ("targets", "contextTargets", "rules", "prerequisites"):
                        c.pop(k, None)
        else:
            out.pop("environments")
        items.append(out)
    if sort:
        s = sort.split(",")[0]
        if s.lstrip("-") in ("key", "name", "creationDate"):
            items.sort(key=lambda x: x[s.lstrip("-")], reverse=s.startswith("-"))
    return page(q, items, path, 20, 100)


