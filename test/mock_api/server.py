SEGMENT_FILTER = {"tags": {"anyOf"}, "query": {"equals"}, "unbounded": {"equals"}, "includedKeys": {"anyOf"},
                  "excludedKeys": {"anyOf"}, "external": {"exists"}}


def r_segments(q, path, m):
    p = project(m[1])
    if m[2] not in env_keys(p):
        raise not_found("environment")
    terms = op_filter(one(q, "filter"), SEGMENT_FILTER)
    sort = one(q, "sort")
    if sort:
        for s in sort.split(","):
            if s.lstrip("-") not in {"creationDate", "name", "lastModified"}:
                raise bad(f"unknown sort field {s!r}")
    items = []
    for s in ACCOUNT["segments"].get(f"{m[1]}/{m[2]}", []):
        keep = True
        for field, _op, val in terms:
            if field == "tags":
                keep &= bool(set(val) & set(s["tags"]))
            elif field == "query":
                if not isinstance(val, str):
                    raise bad("query equals needs a string")
                keep &= val.lower() in " ".join([s["key"], s["name"], s.get("description", "")]).lower()
            elif field == "unbounded":
                if not isinstance(val, bool):
                    raise bad("unbounded equals needs true or false")
                keep &= s.get("unbounded", False) == val
            elif field == "includedKeys":
                keep &= s["key"] in val
            elif field == "excludedKeys":
                keep &= s["key"] not in val
            elif field == "external":
                keep &= "_external" in s
        if keep:
            items.append(s)
    return page(q, items, path, 20, 50)


