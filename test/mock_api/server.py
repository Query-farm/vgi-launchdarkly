class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, format: str, *args: object) -> None:  # noqa: A002 - stdlib signature
        """Log to stderr only, so stdout carries nothing except the ``PORT:`` line."""
        sys.stderr.write("launchdarkly_mock: " + (format % args) + "\n")

    def _send(self, status: int, body: object, headers: dict | None = None) -> None:
        payload = json.dumps(body).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(payload)))
        rl = {
            "X-Ratelimit-Global-Remaining": "1000",
            "X-Ratelimit-Route-Remaining": "100",
            "X-Ratelimit-Reset": str(int(time.time() * 1000) + 10_000),
        }
        rl.update(headers or {})
        for k, v in rl.items():
            self.send_header(k, v)
        self.end_headers()
        self.wfile.write(payload)

    def _record(self, path: str, query: dict, auth: str) -> None:
        q = {k: (v[0] if len(v) == 1 else v) for k, v in query.items()}
        with LOCK:
            REQUESTS.append({"seq": len(REQUESTS) + 1, "path": path, "query": json.dumps(q, sort_keys=True), "auth": auth})

    def do_GET(self) -> None:
        url = urlparse(self.path)
        query = parse_qs(url.query, keep_blank_values=True)
        if url.path == "/health":
            self._send(200, {"status": "ok"})
            return
        if url.path == "/__requests":
            want = (query.get("path") or [None])[0]
            with LOCK:
                rows = [r for r in REQUESTS if not want or r["path"] == want]
            self._send(200, rows)
            return
        try:
            path = unquote(url.path)
            for pattern, fn, allowed in ROUTES:
                m = re.fullmatch(pattern, url.path)
                if not m:
                    continue
                auth_ok = self.headers.get("Authorization", "") == TOKEN
                self._record(path, query, "ok" if auth_ok else "bad")
                if not auth_ok:
                    raise ApiError(401, "unauthorized", "Invalid access token")
                version = self.headers.get("LD-API-Version")
                if version != API_VERSION:
                    raise bad(f"LD-API-Version must be {API_VERSION} for this endpoint (got {version!r})")
                unknown = set(query) - allowed
                if unknown:
                    raise bad(f"unknown query parameter(s): {sorted(unknown)}")
                for key, status in (("/api/v2/teams", 429), ("/api/v2/roles", 503)):
                    if url.path == key:
                        with LOCK:
                            first = key not in ONCE
                            ONCE.add(key)
                        if first and status == 429:
                            raise ApiError(429, "rate_limited", "You've exceeded the API rate limit. Try again later.", {
                                "X-Ratelimit-Route-Remaining": "0",
                                "X-Ratelimit-Reset": str(int(time.time() * 1000) + 1000),
                                "Retry-After": "1",
                            })
                        if first:
                            raise ApiError(503, "service_unavailable", "Service unavailable")
                groups = [m[0], *(unquote(g) for g in m.groups())]
                self._send(200, fn(query, quote(path), groups))
                return
            raise not_found(f"endpoint {url.path}")
        except ApiError as e:
            self._send(e.status, {"code": e.code, "message": e.message}, e.headers)


def main() -> None:
    """Serve until interrupted, printing ``PORT:<n>`` once bound."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--port", type=int, default=0, help="port to bind (default: any free port)")
    args = parser.parse_args()
    server = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)
    print(f"PORT:{server.server_address[1]}", flush=True)
    with contextlib.suppress(KeyboardInterrupt):
        server.serve_forever()


if __name__ == "__main__":
    main()
